import React, { useState } from 'react';
import { API_BASE_URL } from '../../lib/api';
import type { Employee } from '../../types';

const DEPARTMENTS = [
  'Housekeeping',
  'Front Desk',
  'Restaurant',
  'Kitchen',
] as const;

type Department = (typeof DEPARTMENTS)[number];

interface DepartmentAssignment {
  required_staff: number;
  assigned_staff: number;
  assigned_employees: string[];
  unfilled_positions: number;
  status: string;
}

interface RosterDay {
  date: string;
  predicted_arrivals: number;
  departments: Record<Department, DepartmentAssignment>;
}

interface OptimizedRosterResponse {
  status: string;
  solver_status: string;
  model: string;
  training_data_last_date: string;
  horizon_days: number;
  daily_roster: RosterDay[];
  employee_total_shifts: Record<string, number>;
  summary: {
    required_positions: number;
    assigned_positions: number;
    unfilled_positions: number;
  };
  workload_assumptions?: Record<string, number>;
  optimization?: {
    coverage_positions: number;
    fairness_cost: number;
    repeated_previous_assignments: number;
    priorities?: string[];
  };
  note: string;
}

interface Props {
  employees: Employee[];
  onTriggerToast: (message: string) => void;
}

const initialWorkload: Record<Department, number> = {
  Housekeeping: 15,
  'Front Desk': 60,
  Restaurant: 30,
  Kitchen: 40,
};

const isOptimizerRestDay = (
  shift: Employee['shifts'][number]
): boolean =>
  shift.status === 'Unavailability' &&
  shift.role === 'Rest day' &&
  shift.shiftLabel === 'OFF';

export const OptimizedRosterPanel: React.FC<Props> = ({
  employees,
  onTriggerToast,
}) => {
  const [horizonDays, setHorizonDays] = useState(7);
  const [workload, setWorkload] = useState(initialWorkload);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [result, setResult] =
    useState<OptimizedRosterResponse | null>(null);

  const eligibleEmployees = employees.filter((employee) =>
    (DEPARTMENTS as readonly string[]).includes(
      employee.department.trim()
    )
  );

  const excludedEmployees =
    employees.length - eligibleEmployees.length;

  const generateRoster = async () => {
    setError(null);
    setResult(null);
    setLoading(true);

    try {
      if (eligibleEmployees.length === 0) {
        throw new Error(
          'No employees belong to the four supported departments.'
        );
      }

      const employeeNames = eligibleEmployees.map((employee) =>
        employee.name.trim().toLowerCase()
      );

      if (new Set(employeeNames).size !== employeeNames.length) {
        throw new Error(
          'Employee names must be unique to generate a roster.'
        );
      }

      for (const department of DEPARTMENTS) {
        const ratio = workload[department];

        if (
          !Number.isFinite(ratio) ||
          ratio <= 0
        ) {
          throw new Error(
            `Enter a positive workload ratio for ${department}.`
          );
        }
      }

      const blockedStatuses = new Set([
        'Leave',
        'Sick Leave',
        'Vacation',
        'Unavailability',
      ]);

      const employeesForApi = eligibleEmployees.map((employee) => {
        // Genuine leave and unavailable days remain protected.
        // Rest days generated by QuickShift remain eligible.
        const unavailableDays = [
          ...new Set(
            employee.shifts
              .filter(
                (shift) =>
                  blockedStatuses.has(shift.status) &&
                  !isOptimizerRestDay(shift)
              )
              .map((shift) => shift.dayIndex + 1)
              .filter(
                (day) => day >= 1 && day <= horizonDays
              )
          ),
        ];

        // Tell the backend which days this employee worked
        // in the currently applied roster, so it can rotate
        // assignments when coverage and fairness allow.
        const previousAssignedDays = [
          ...new Set(
            employee.shifts
              .filter((shift) => shift.status === 'Confirmed')
              .map((shift) => shift.dayIndex + 1)
              .filter(
                (day) => day >= 1 && day <= horizonDays
              )
          ),
        ];

        return {
          name: employee.name.trim(),
          departments: [employee.department.trim()],
          unavailable_days: unavailableDays,
          previous_assigned_days: previousAssignedDays,
          max_shifts: Math.min(
            5,
            Math.max(
              0,
              Math.ceil(
                (employee.totalWeeklyHours || 40) / 8
              )
            )
          ),
        };
      });

      const response = await fetch(
        `${API_BASE_URL}/api/optimize-staffing-schedule`,
        {
          method: 'POST',
          headers: {
            'Content-Type': 'application/json',
          },
          body: JSON.stringify({
            horizon_days: horizonDays,
            bookings_per_staff_per_day: workload,
            employees: employeesForApi,
          }),
        }
      );

      const body = await response.json().catch(() => ({}));

      if (!response.ok) {
        const detail = body.detail;

        throw new Error(
          typeof detail === 'string'
            ? detail
            : detail
              ? JSON.stringify(detail)
              : `Request failed with HTTP ${response.status}.`
        );
      }

      if (
        body.status !== 'success' ||
        !Array.isArray(body.daily_roster) ||
        !body.summary ||
        !body.employee_total_shifts
      ) {
        throw new Error(
          'The backend returned an unexpected optimization response.'
        );
      }

      setResult(body as OptimizedRosterResponse);

      onTriggerToast(
        'Optimized roster generated from the backend.'
      );
    } catch (err) {
      const message =
        err instanceof Error
          ? err.message
          : 'Could not generate the roster.';

      setError(message);
      onTriggerToast('Roster generation failed.');
    } finally {
      setLoading(false);
    }
  };

  const formatDate = (date: string) =>
    new Date(`${date}T12:00:00`).toLocaleDateString(undefined, {
      weekday: 'short',
      month: 'short',
      day: 'numeric',
      year: 'numeric',
    });

  const coveragePercent =
    result && result.summary.required_positions > 0
      ? Math.round(
          (result.summary.assigned_positions /
            result.summary.required_positions) *
            100
        )
      : result
        ? 100
        : 0;

  return (
    <section className="bg-white rounded-xl border border-slate-200 p-5 sm:p-6 shadow-sm mb-6">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-start sm:justify-between gap-3">
        <div>
          <div className="flex items-center gap-2 flex-wrap">
            <h2 className="text-lg font-extrabold text-slate-900">
              Optimized Staffing Roster
            </h2>

            <span className="px-2 py-1 rounded-full bg-teal-50 text-teal-800 border border-teal-100 text-[10px] font-bold">
              OR-Tools
            </span>
          </div>

          <p className="text-sm text-slate-500 mt-1">
            Convert forecast arrivals into proposed department assignments,
            balance workloads, and identify staffing shortages.
          </p>
        </div>

        <div className="text-xs text-slate-500">
          Eligible employees:{' '}
          <strong className="text-slate-800">
            {eligibleEmployees.length}
          </strong>
        </div>
      </div>

      {/* Workload assumptions */}
      <div className="mt-5">
        <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-3 mb-3">
          <h3 className="text-sm font-bold text-slate-800">
            Workload assumptions
          </h3>

          <label className="flex items-center gap-2 text-xs text-slate-600">
            Forecast horizon

            <select
              value={horizonDays}
              onChange={(event) => {
                setHorizonDays(Number(event.target.value));
                setResult(null);
                setError(null);
              }}
              className="border border-slate-200 rounded-lg p-2 bg-white"
              disabled={loading}
            >
              <option value={7}>7 days</option>
              <option value={14}>14 days</option>
            </select>
          </label>
        </div>

        <p className="text-xs text-slate-500 mb-3">
          Assumed arrival records handled per employee per day.
          These are editable prototype assumptions, not validated
          industry standards.
        </p>

        <div className="grid grid-cols-2 lg:grid-cols-4 gap-3">
          {DEPARTMENTS.map((department) => (
            <label
              key={department}
              className="block rounded-lg border border-slate-200 p-3"
            >
              <span className="block text-xs font-semibold text-slate-700 mb-2">
                {department}
              </span>

              <input
                type="number"
                min="1"
                step="1"
                value={workload[department]}
                disabled={loading}
                onChange={(event) => {
                  const value = Number(event.target.value);

                  setWorkload((previous) => ({
                    ...previous,
                    [department]: value,
                  }));

                  setResult(null);
                  setError(null);
                }}
                className="w-full rounded-md border border-slate-200 px-3 py-2 text-sm text-slate-900 outline-none focus:border-teal-600"
              />
            </label>
          ))}
        </div>

        {excludedEmployees > 0 && (
          <p className="text-xs text-slate-500 mt-3">
            {excludedEmployees} employee record(s) are excluded because
            their department is not currently supported by this optimizer.
          </p>
        )}

        <button
          type="button"
          onClick={generateRoster}
          disabled={loading}
          className="mt-4 inline-flex items-center justify-center gap-2 rounded-xl bg-teal-700 px-5 py-3 text-sm font-bold text-white hover:bg-teal-800 disabled:opacity-60 transition-colors"
        >
          {loading ? (
            <>
              <span className="material-symbols-outlined animate-spin">
                progress_activity
              </span>
              Generating roster...
            </>
          ) : (
            <>
              <span className="material-symbols-outlined text-lg">
                calendar_check
              </span>
              Generate Optimized Roster
            </>
          )}
        </button>
      </div>

      {/* Error */}
      {error && (
        <div
          role="alert"
          className="mt-4 rounded-lg border border-rose-200 bg-rose-50 p-3 text-sm text-rose-700"
        >
          {error}
        </div>
      )}

      {/* Actual backend results */}
      {result && (
        <div className="mt-6 border-t border-slate-100 pt-5">
          <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-2 mb-4">
            <div>
              <h3 className="text-base font-bold text-slate-900">
                Proposed roster
              </h3>

              <p className="text-xs text-slate-500 mt-1">
                Solver status: {result.solver_status}
                {' · '}
                Training data through{' '}
                {result.training_data_last_date}
              </p>
            </div>

            <span
              className={`text-xs font-bold rounded-full px-3 py-1 ${
                result.summary.unfilled_positions > 0
                  ? 'bg-rose-50 text-rose-700'
                  : 'bg-emerald-50 text-emerald-700'
              }`}
            >
              {result.summary.unfilled_positions > 0
                ? `${result.summary.unfilled_positions} positions unfilled`
                : 'All estimated positions covered'}
            </span>
          </div>

          {/* Summary KPIs */}
          <div className="grid grid-cols-2 sm:grid-cols-4 gap-3 mb-5">
            {[
              {
                label: 'Required positions',
                value: result.summary.required_positions,
              },
              {
                label: 'Assigned positions',
                value: result.summary.assigned_positions,
              },
              {
                label: 'Unfilled positions',
                value: result.summary.unfilled_positions,
              },
              {
                label: 'Coverage',
                value: `${coveragePercent}%`,
              },
            ].map((item) => (
              <div
                key={item.label}
                className="rounded-xl border border-slate-100 bg-slate-50 p-4"
              >
                <p className="text-xs text-slate-500">
                  {item.label}
                </p>

                <p className="text-2xl font-extrabold text-slate-900 mt-1">
                  {item.value}
                </p>
              </div>
            ))}
          </div>

          {/* Rotation and fairness diagnostics */}
          {result.optimization && (
            <div className="rounded-xl border border-slate-200 p-4 mb-5">
              <h4 className="text-sm font-bold text-slate-900">
                Optimization diagnostics
              </h4>

              <div className="grid grid-cols-1 sm:grid-cols-3 gap-3 mt-3">
                <div>
                  <p className="text-xs text-slate-500">
                    Coverage objective
                  </p>
                  <p className="text-lg font-bold text-slate-900 mt-1">
                    {result.optimization.coverage_positions}
                  </p>
                </div>

                <div>
                  <p className="text-xs text-slate-500">
                    Workload fairness cost
                  </p>
                  <p className="text-lg font-bold text-slate-900 mt-1">
                    {result.optimization.fairness_cost}
                  </p>
                  <p className="text-[10px] text-slate-400">
                    Lower is better when coverage is equal.
                  </p>
                </div>

                <div>
                  <p className="text-xs text-slate-500">
                    Previous day assignments repeated
                  </p>
                  <p className="text-lg font-bold text-slate-900 mt-1">
                    {result.optimization.repeated_previous_assignments}
                  </p>
                  <p className="text-[10px] text-slate-400">
                    Lower indicates more day-level rotation.
                  </p>
                </div>
              </div>
            </div>
          )}

          {/* Daily schedule */}
          <div className="space-y-3">
            {result.daily_roster.map((day) => (
              <details
                key={day.date}
                className="rounded-xl border border-slate-200 overflow-hidden"
              >
                <summary className="cursor-pointer p-4 bg-slate-50 hover:bg-slate-100">
                  <span className="font-bold text-sm text-slate-900">
                    {formatDate(day.date)}
                  </span>

                  <span className="ml-2 text-xs text-slate-500">
                    {Math.round(day.predicted_arrivals)} predicted arrivals
                  </span>
                </summary>

                <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 p-3">
                  {DEPARTMENTS.map((department) => {
                    const assignment = day.departments[department];

                    if (!assignment) {
                      return (
                        <div
                          key={department}
                          className="rounded-lg border border-amber-200 bg-amber-50 p-3"
                        >
                          <h4 className="font-bold text-sm text-amber-800">
                            {department}
                          </h4>
                          <p className="text-xs text-amber-700 mt-2">
                            No department result was returned.
                          </p>
                        </div>
                      );
                    }

                    return (
                      <div
                        key={department}
                        className="rounded-lg border border-slate-100 p-3"
                      >
                        <div className="flex items-start justify-between gap-2">
                          <h4 className="font-bold text-sm text-slate-800">
                            {department}
                          </h4>

                          <span
                            className={`text-[10px] font-bold rounded-full px-2 py-1 ${
                              assignment.unfilled_positions > 0
                                ? 'bg-rose-50 text-rose-700'
                                : 'bg-emerald-50 text-emerald-700'
                            }`}
                          >
                            {assignment.unfilled_positions > 0
                              ? `${assignment.unfilled_positions} unfilled`
                              : 'Covered'}
                          </span>
                        </div>

                        <p className="text-xs text-slate-500 mt-2">
                          Required: {assignment.required_staff}
                          {' · '}
                          Assigned: {assignment.assigned_staff}
                        </p>

                        <div className="flex flex-wrap gap-1.5 mt-3">
                          {assignment.assigned_employees.length > 0 ? (
                            assignment.assigned_employees.map((name) => (
                              <span
                                key={name}
                                className="rounded-md bg-teal-50 text-teal-800 px-2 py-1 text-[11px] font-medium"
                              >
                                {name}
                              </span>
                            ))
                          ) : (
                            <span className="text-xs text-slate-400">
                              No employees assigned
                            </span>
                          )}
                        </div>
                      </div>
                    );
                  })}
                </div>
              </details>
            ))}
          </div>

          {/* Employee workload totals */}
          <div className="mt-5">
            <h4 className="text-sm font-bold text-slate-800 mb-2">
              Shifts per employee
            </h4>

            <div className="flex flex-wrap gap-2">
              {Object.entries(result.employee_total_shifts).map(
                ([name, shifts]) => (
                  <span
                    key={name}
                    className="rounded-lg border border-slate-200 px-3 py-2 text-xs text-slate-700"
                  >
                    {name}: <strong>{shifts}</strong>
                  </span>
                )
              )}
            </div>
          </div>

          <p className="text-xs leading-relaxed text-slate-500 mt-4">
            {result.note}
          </p>

          <p className="text-xs text-slate-500 mt-2">
            This is a proposed schedule. Generating it does not apply it
            to the current roster. Use the Smart Roster modal to review
            and apply assignments to the live in-memory roster.
          </p>
        </div>
      )}
    </section>
  );
};